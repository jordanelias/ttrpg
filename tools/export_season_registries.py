#!/usr/bin/env python3
"""Export the season's registries to one typed-JSON artifact the Godot port reads, so it never reads the YAML.

WHY THIS EXISTS (GO-09). The season loop reads its data from YAML files that `engine/season/data/files.py`
names and a loader under `engine/season/data/` parses. The port reads typed artifacts, not YAML
(`engine/engine_params/`); this tool is the writer half for the season's registries, in the shape of
`export_game_constants.py` and `export_composition.py`: one owner (the YAML), one exporter with a blocking
`--check` round trip, one artifact. A registry edited without a re-export reds `--check`; a batch that
edits a registry this artifact copies re-runs `--build` (the default mode) in the same commit.

WHICH FILES. Exactly the files a module under `engine/season/data/` passes to `rosters.load_yaml`
(`grep -n "load_yaml(" engine/season/data/*.py`), each named by its `files.<NAME>` constant, never by a
path spelled here. `SOURCES` lists those constants. A loader that starts parsing a further file leaves
that file out of the artifact until its constant is added here; `files.py` stays the one owner of every
path.

HOW IT PARSES. With `rosters.load_yaml`, the loaders' own parser, which refuses a duplicate mapping key.
Never a bare `yaml.safe_load`: it silently keeps the last of two identical keys, so the artifact would
copy a document the loaders refuse.

LOSSLESSLY. `build()` raises, naming the file and the key path, on a value JSON cannot carry unchanged
(a non-string mapping key, a date, a set, a non-finite float, a tuple). It never coerces.

WHAT IT DOES NOT HOLD. `DEFAULT_FIXTURES` (the season's settings) is NOT written here: `engine/engine_params/
sim_params.json` already carries every literal `DEFAULT_FIXTURES` keyword under `engine.season.settings`
(`tools/export_sim_params.py`), and a second export of the same values would be a second owner.

Usage:
    python3 tools/export_season_registries.py           # (--build) write engine/engine_params/season_registries.json
    python3 tools/export_season_registries.py --build   # same
    python3 tools/export_season_registries.py --check   # re-derive and diff vs committed (exit 1 on drift)
"""
from __future__ import annotations

import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ci_common  # noqa: E402

REPO = ci_common.REPO
OUT = os.path.join(REPO, 'engine', 'engine_params', 'season_registries.json')

if REPO not in sys.path:
    sys.path.insert(0, REPO)

# The `files.<NAME>` constants a loader under engine/season/data/ passes to `load_yaml`, read by symbol.
# `NPC_REGISTRY_YAML` is the cast's file, parsed by `data/cast.py` through `files.NPC_REGISTRY_YAML`.
SOURCES = (
    'ARRANGEMENTS_YAML',
    'GEOGRAPHY_YAML',
    'GOALS_YAML',
    'NPC_REGISTRY_YAML',
    'OFFICES_YAML',
    'ROSTERS_YAML',
    'VERB_TABLE_YAML',
    'WRITE_MATRIX_YAML',
)


def _refuse_unless_lossless(node, where):
    """Raise on a value JSON would coerce or reject, naming the file and the key path."""
    if node is None or isinstance(node, (bool, int, str)):
        return
    if isinstance(node, float):
        if not math.isfinite(node):
            raise ValueError(f'{where}: non-finite float {node!r} is not JSON')
        return
    if type(node) is dict:
        for k, v in node.items():
            if not isinstance(k, str):
                raise ValueError(f'{where}: mapping key {k!r} is a {type(k).__name__}, not a string; '
                                 f'JSON would coerce it')
            _refuse_unless_lossless(v, f'{where}.{k}')
        return
    if type(node) is list:
        for i, v in enumerate(node):
            _refuse_unless_lossless(v, f'{where}[{i}]')
        return
    raise ValueError(f'{where}: a {type(node).__name__} ({node!r}) is not carried unchanged by JSON')


def _sources():
    """`{repo-relative posix path: absolute Path}` for every file in SOURCES, sorted by path."""
    from engine.season.data import files
    out = {}
    for name in SOURCES:
        p = getattr(files, name)
        out[p.resolve().relative_to(files.REPO_ROOT).as_posix()] = p
    return dict(sorted(out.items()))


def build(overrides=None) -> dict:
    """The artifact. `overrides` ({repo-relative path: Path}) reads that Path in place of the named file;
    it is the test seam, so a registry edited without a re-export can be shown to red the check."""
    from engine.season.data.rosters import load_yaml
    overrides = overrides or {}
    parsed = {}
    for rel, path in _sources().items():
        text = (overrides.get(rel, path)).read_text(encoding='utf-8')
        doc = load_yaml(text)
        _refuse_unless_lossless(doc, rel)
        parsed[rel] = doc
    return {
        '_generated': ('GENERATED by tools/export_season_registries.py from the files listed under `files`; '
                       'never hand-edited: edit the YAML, re-run the tool, commit both together.'),
        'schema_version': 1,
        'source': 'engine/season/data/files.py',
        'files': parsed,
    }


def main(argv, overrides=None):
    out = OUT
    data = build(overrides)
    text = json.dumps(data, indent=2, sort_keys=False) + '\n'
    if '--check' in argv:
        if not os.path.exists(out):
            print(f'[season-registries] MISSING {os.path.relpath(out, REPO)} — run without --check.')
            return 1
        with open(out, encoding='utf-8') as fh:
            committed = fh.read()
        if committed != text:
            print(f'[season-registries] DRIFT — {os.path.relpath(out, REPO)} is stale. '
                  f'Run: python3 tools/export_season_registries.py')
            return 1
        print(f'[season-registries] OK — {len(data["files"])} file(s)')
        return 0
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print(f'[season-registries] wrote {os.path.relpath(out, REPO)} — {len(data["files"])} file(s).')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))

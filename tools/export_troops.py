#!/usr/bin/env python3
"""Cook the troop file (`references/troops.yaml`) into the artifact the mass-battle module reads.

WHY THIS EXISTS (B17.10). A kind of soldier used to be twelve tables in five files; it is now one row of
`references/troops.yaml`, whose arms, classes, role specs and closed sets sit beside it. The module reads the typed
artifact `engine/engine_params/troops.json` through `modules/mass_battle/troop_types/table.py` (a data file, no `engine`
import), and the port reads the same artifact. Same shape as `export_battle_orders.py`: one authored head, one exporter
with a blocking `--check`, one artifact. A hand edit of the JSON fails `--check`; a row edit re-runs this tool.

WHAT IT REFUSES. Everything `table.check` refuses (an unknown or missing column; a row naming an arm, armour tier, role
or site kind outside its closed set; an arm whose mass is stated here and in personal combat's export; a `secondary`
equal to the `primary`) -- the one validator, so the loader and this tool cannot disagree -- and a `site_kinds` member
that is not one of the season's own (`engine/engine_params/season_registries.json`, `rosters.yaml: site_kinds`).

TWO ARTIFACTS, ONE DOCUMENT. `engine/engine_params/troops.json` is the port's; `modules/mass_battle/troop_types/
troops_data.py` is the same document as a Python literal, because a registered module opens no file (A-25) and so cannot
read the JSON while a field is fought. `--check` re-derives both and reds on either one stale, so neither is a second owner.

Usage:
    python3 tools/export_troops.py           # write both artifacts
    python3 tools/export_troops.py --check   # re-derive and diff vs committed (exit 1 on drift)
"""
from __future__ import annotations

import ast
import json
import os
import pprint
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ci_common  # noqa: E402

REPO = ci_common.REPO
if REPO not in sys.path:
    sys.path.insert(0, REPO)

SRC = os.path.join(REPO, 'references', 'troops.yaml')
OUT = os.path.join(REPO, 'engine', 'engine_params', 'troops.json')
OUT_PY = os.path.join(REPO, 'modules', 'mass_battle', 'troop_types', 'troops_data.py')
SCHEMA_VERSION = 1


def _engine_config_names() -> frozenset:
    """The field names of `config.EngineConfig`, read from `config.py`'s syntax and never by import: `config` imports the troop
    literal this exporter writes, so importing it here would stop the exporter regenerating a missing or stale literal."""
    path = os.path.join(REPO, 'modules', 'mass_battle', 'config.py')
    with open(path, encoding='utf-8') as fh:
        tree = ast.parse(fh.read())
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == 'EngineConfig')
    return frozenset(n.target.id for n in cls.body if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name))


def build() -> dict:
    """The artifact: the file's sections in the loader's order, behind the loader's own refusals."""
    from engine.season.data.rosters import SITE_KINDS, load_yaml   # load_yaml refuses a duplicate key: two rows of one name are an error
    from modules.mass_battle.troop_types import table
    with open(SRC, encoding='utf-8') as fh:
        src = load_yaml(fh.read())
    table.check(src, config_names=_engine_config_names())      # a name has one owner, never the file and `EngineConfig`
    unknown = sorted(set(src['site_kinds']) - SITE_KINDS)
    if unknown:
        raise ValueError(f'site_kinds {unknown} are not members of the season\'s site_kinds')
    out = {
        '_generated': 'tools/export_troops.py -- do not hand-edit; edit references/troops.yaml',
        'schema_version': SCHEMA_VERSION,
        'source': 'references/troops.yaml',
    }
    out.update({k: src[k] for k in table.HEADER_KEYS})
    return out


def literal(data: dict) -> str:
    """The module-side artifact: the document as a Python literal, `DATA`."""
    return ('"""GENERATED by tools/export_troops.py from references/troops.yaml -- do not hand-edit.\n\n'
            'The troop file as a Python literal, read by `table.py`: a registered module opens no file (A-25).\n'
            'engine/engine_params/troops.json is the same document for the port; `export_troops.py --check` pins them equal."""\n'
            f'DATA = {pprint.pformat(data, width=140, sort_dicts=False, compact=True)}\n')


def main(argv):
    try:
        data = build()
    except Exception as exc:                                      # a refusal is named and exits non-zero, never a traceback
        print(f'[troops] REFUSED -- {exc}')
        return 1
    want = {OUT: json.dumps(data, indent=2, ensure_ascii=False) + '\n', OUT_PY: literal(data)}
    if '--check' in argv:
        for path, text in want.items():
            if not os.path.exists(path):
                print(f'[troops] MISSING {os.path.relpath(path, REPO)} -- run without --check.')
                return 1
            if open(path, encoding='utf-8').read() != text:
                print(f'[troops] DRIFT -- {os.path.relpath(path, REPO)} is stale. Run: python3 tools/export_troops.py')
                return 1
        print(f'[troops] OK -- {len(data["troops"])} troop rows, {len(data["arms"])} arms, {len(data["classes"])} classes.')
        return 0
    for path, text in want.items():
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(text)
        print(f'[troops] wrote {os.path.relpath(path, REPO)}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
